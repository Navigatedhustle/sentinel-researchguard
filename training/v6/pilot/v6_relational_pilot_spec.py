def permission_yes():

    return PolicyState(
        applicability=Applicability.ESTABLISHED,
        base_rule=BaseRule.PERMISSION,
        requirements=(
            Requirement(
                "required review complete",
                RequirementState.SATISFIED,
            ),
        ),
    )


def permission_no():

    return PolicyState(
        applicability=Applicability.ESTABLISHED,
        base_rule=BaseRule.PERMISSION,
        requirements=(
            Requirement(
                "required review complete",
                RequirementState.FAILED,
            ),
        ),
    )


def direct_no():

    return PolicyState(
        applicability=Applicability.ESTABLISHED,
        base_rule=BaseRule.PROHIBITION,
    )


def permission_conditional():

    return PolicyState(
        applicability=Applicability.ESTABLISHED,
        base_rule=BaseRule.PERMISSION,
        requirements=(
            Requirement(
                "required review complete",
                RequirementState.UNRESOLVED,
            ),
        ),
    )


def insufficient():

    return PolicyState(
        applicability=Applicability.UNRESOLVED,
        base_rule=BaseRule.NONE,
    )


